"""recording_aug.py — recording-condition augmentation (the `gugak_mix.recording_aug` block).

WHY THIS EXISTS. 71955 was captured in ONE studio. Every stem of every song shares the
same room, the same close-miking and the same chain, so the corpus has effectively zero
INTER-RECORDING acoustic variance — and cross-song incoherent mixing manufactures none,
because every song it draws from was recorded under identical conditions. MUSDB gets that
diversity for free (its songs come from many studios); we have to synthesize it. A model
trained here only ever sees one acoustic path, and deployment audio is not close-miked:
it is picked up at some distance, in an unknown room. Supplying that missing axis is what
this module is for, and room simulation is rank 1 for that reason, NOT because reverb per
se is the deployment problem.

THE SYMMETRIC MISTAKE, avoided by design: do not manufacture variance in the dimension the
corpus is RIGHT about. A real recording puts every instrument in ONE space behind ONE
acoustic path, so giving each stem its own room would hand the separator a "which room is
this" cue that is perfectly informative in training and simply absent at test time. The
room therefore varies ACROSS mixtures and is SHARED WITHIN one (→ RirConfig).

Five stages, each independently gated, each with an explicit target policy (the algebra is
in the survey report §4; evidence classes below are its convention — MEASURED = a paper
reports a controlled comparison, RECIPE = a released generator demonstrates the synthesis,
INFERENCE = derived from those plus the sum algebra, i.e. not a reported Gugak result):

  1. device / capture response — per-stem minimum-phase biquad cascade. Linear, so
     T(Σ s_i) = Σ T(s_i): apply to every target and the sum survives untouched.
     COUPLED TO DISTANCE by default (→ DeviceResponseConfig).
  2. room  — convolution with a synthetic RIR bank. `source_image` targets (h_i * s_i,
     mixture Σ_i h_i * s_i) keep the sum EXACT for any choice of h_i, so the scope knob
     is free to be whatever is physically right rather than whatever the algebra allows;
     the default is one shared h per mixture. `dry_source` is the dereverberation task and
     is a separate coherence_mode, never a default.
  3. level automation — a gain envelope shared by mixture and every target (capture-level
     drift), or independent per stem (fader/production drift). Both sum-preserving,
     because the mixture is rebuilt as the sum AFTER the envelope is applied.
  4. mix-bus loudness + limiting (LimitAug) — the only NONLINEAR stage. D(Σ s_i) ≠ Σ D(s_i),
     so targets are bus-affected source images: r[t] = m'[t]/m[t] where the mixture is
     above the silence floor, y_i = r·s_i, and the float residual m' − Σ y_i is pushed
     onto the largest stem at each sample so the sum is exact again (report §4.3).
  5. dirty input — noise / resample / quantize / clip on the MIXTURE ONLY, targets clean.
     This DELIBERATELY breaks mixture ≡ Σ targets and is reachable only under
     `coherence_mode: clean_under_degraded_input`.

OFF IS FREE. An absent or `enable: false` block draws not one value from the item RNG and
runs not one line of the realisation path, so every pre-existing config (exp003.x, exp004.x,
exp006) stays bit-identical — proved against the pre-change module by
tests/test_recording_aug.py::test_off_by_default_is_bit_identical. Within an enabled block
each stage with probability 0 likewise consumes nothing, following the convention
`GugakMixDataset._draw_coherent_count` already set for p = 0.

ALL RANDOMNESS IS DRAWN IN THE PLAN. `RecordingAugmenter.plan()` is called from
`GugakMixDataset._plan_item` with the item's `np.random.default_rng([seed, index])` and
returns a fully-decided `RecordingPlan`; the realisation half touches no RNG. Audio is
never read at plan time, so `plan_item()` still works with no RIR bank on disk.

LICENSING. Everything here is NumPy/SciPy (BSD) plus soundfile (BSD-3). The RIR bank is
generated by scripts/build_rir_pool.py with pyroomacoustics (MIT) and is therefore our own
artifact with no third-party corpus terms attached — report §3.3 flags that the licence
situation of the measured corpora (EchoThief unusable, MIT IR Survey unclear, BUT/OpenAIR
attribution-bound) needs an audit before shipping. Pedalboard (GPLv3) is deliberately NOT
used by any stage added here; the existing stem/mix-bus EQ still uses it.
"""
