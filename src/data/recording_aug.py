@dataclass
class LimitAugConfig:
    """Stage 4 — mix-bus loudness and limiting (LimitAug), the only nonlinear stage.

    Evidence: the best-MEASURED technique in the whole report (Jeon & Lee, ISMIR 2022:
    LimitAug recovers ~.22–.85 dB of the musdb-L/XL out-of-domain loss and can improve
    in-domain). It is implemented here in full BECAUSE it is cheap and well-measured —
    but it models loudness-war MASTERING mismatch, a POST-PRODUCTION axis, and the
    deployment gap this project is chasing is CAPTURE-side. It is therefore off in exp007.

    THE NORMALIZATION ORDER IS THE TRAP. `GugakMixDataset._normalize` returns every
    mixture to −19 LUFS. Run after the limiter it erases exactly the loudness diversity
    LimitAug exists to create, leaving only the limiter's waveform distortion — report
    §5.1 flags this explicitly. Hence:
      loudness_mode: sampled   draw the PRE-bus target loudness per item, N(mean, std)
      normalize_after_bus: false   the post-bus operation is a shared peak guard only
    Setting `loudness_mode: fixed` + `normalize_after_bus: true` reproduces the old
    behaviour and gives the "limiter shape without loudness shift" control arm.

    Ranges: target loudness N(−14, 2) LUFS is report §5.1's first-Gugak-arm suggestion
    (N(−10.9, 1.2) is the loud-broadcast match, measured from musdb-L); threshold 0 dBFS
    and release U(30, 200) ms are the paper's own settings.
    """
    prob: float = 0.0
    loudness_mode: str = "fixed"
    target_lufs_mean: float = -14.0
    target_lufs_std: float = 2.0
    threshold_dbfs: float = 0.0
    release_ms: list = field(default_factory=lambda: [30.0, 200.0])
    attack_ms: float = 1.5
    normalize_after_bus: bool = True
    residual_correction: bool = True

    @classmethod
    def from_mapping(cls, mapping: dict) -> "LimitAugConfig":
        cfg = cls(**_reject_unknown(cls, mapping, "recording_aug.limit_aug"))
        if cfg.loudness_mode not in LOUDNESS_MODES:
            raise ValueError(f"recording_aug.limit_aug.loudness_mode="
                             f"{cfg.loudness_mode!r}: expected {LOUDNESS_MODES}")
        return cfg


@dataclass
class DirtyInputConfig:
    """Stage 5 — degrade the MIXTURE, keep the targets clean. Breaks the sum on purpose.

    Unreachable unless `coherence_mode: clean_under_degraded_input`, and every probability
    defaults to 0 on top of that, so it takes two deliberate edits to turn on. The task it
    defines is separation PLUS denoising/restoration, scored against a different invariant
    (report §4.4), and it must never be mixed into a strict-sum comparison by accident.

    Evidence: LOW-to-MEDIUM. Cross-corpus speech work gets about +.6–1.4 dB from robust
    mixing combinations (Alex et al.), and DNS/WHAM establish the recipe, but report §2.3
    found NO controlled music-separation paper that trains with a codec and reports
    codec-held-out SDR. The numeric ranges are report §5.1's mild starting values.

    CODEC IS DELIBERATELY NOT IMPLEMENTED — `codec_prob > 0` raises. Reasons, in order:
    no measured MSS evidence exists (§2.3); the local measurement is 140–170 ms per 8 s
    item (§3.5), which alone exceeds the entire per-item CPU budget; and MP3/AAC/Opus need
    an ffmpeg and licence audit (§6.1). It is a reserved seam in the repo's sense.
    """
    noise_prob: float = 0.0
    noise_manifest: str | None = None
    noise_audio_root: str | None = None
    noise_snr_db: list = field(default_factory=lambda: [15.0, 35.0])
    resample_prob: float = 0.0
    intermediate_rates: list = field(default_factory=lambda: [16000, 24000, 32000])
    quantize_prob: float = 0.0
    bit_depths: list = field(default_factory=lambda: [12, 16])
    clip_prob: float = 0.0
    clip_dbfs: list = field(default_factory=lambda: [-3.0, -1.0])
    codec_prob: float = 0.0        # reserved seam — nonzero raises (see docstring)

    @classmethod
    def from_mapping(cls, mapping: dict) -> "DirtyInputConfig":
        return cls(**_reject_unknown(cls, mapping, "recording_aug.dirty_input"))

    @property
    def any_enabled(self) -> bool:
        return max(self.noise_prob, self.resample_prob, self.quantize_prob,
                   self.clip_prob, self.codec_prob) > 0.0


@dataclass
class RecordingAugConfig:
    """The `gugak_mix.recording_aug` block. Absent/empty = disabled = byte-identical."""
    enable: bool = False
    # strict_sum              mixture ≡ Σ targets to float tolerance. The only mode any
    #                         existing experiment may use.
    # dereverberation         RIR targets are the DRY stems; the mixture is the sum of the
    #                         wet images. A different TASK, not an augmentation.
    # clean_under_degraded_input   stage 5. The mixture is degraded, the targets are not.
    coherence_mode: str = "strict_sum"
    # the project's silence tolerance (CLAUDE.md: post-ingest silence is a ±1-LSB residue
    # at 1.192e-07, so anything ≥1e-6 is safely above it). Used as the mixture-support
    # floor in the LimitAug ratio and as the sum-invariant assertion tolerance.
    silence_eps: float = 1e-6
    # assert the invariant on every item. Cheap (one reduction), but it is a debug aid:
    # leave it off for production runs and on for smoke/bench.
    assert_invariant: bool = False
    device_response: dict = field(default_factory=dict)
    rir: dict = field(default_factory=dict)
    level_automation: dict = field(default_factory=dict)
    limit_aug: dict = field(default_factory=dict)
    dirty_input: dict = field(default_factory=dict)

    @classmethod
    def from_mapping(cls, mapping: dict) -> "RecordingAugConfig":
        return cls(**_reject_unknown(cls, mapping, "recording_aug"))


@dataclass(frozen=True)
class ResolvedRecordingConfig:
    """The block with its five sub-blocks parsed and cross-validated."""
    enable: bool
    coherence_mode: str
    silence_eps: float
    assert_invariant: bool
    device: DeviceResponseConfig
    rir: RirConfig
    automation: LevelAutomationConfig
    limit: LimitAugConfig
    dirty: DirtyInputConfig

    @classmethod
    def from_mapping(cls, mapping: dict) -> "ResolvedRecordingConfig":
        block = RecordingAugConfig.from_mapping(mapping)
        resolved = cls(enable=bool(block.enable),
                       coherence_mode=str(block.coherence_mode),
                       silence_eps=float(block.silence_eps),
                       assert_invariant=bool(block.assert_invariant),
                       device=DeviceResponseConfig.from_mapping(block.device_response),
                       rir=RirConfig.from_mapping(block.rir),
                       automation=LevelAutomationConfig.from_mapping(
                           block.level_automation),
                       limit=LimitAugConfig.from_mapping(block.limit_aug),
                       dirty=DirtyInputConfig.from_mapping(block.dirty_input))
        resolved.validate()
        return resolved

    def validate(self) -> None:
        """Cross-block rules. The two sum-breaking modes must be unreachable by accident."""
        if self.coherence_mode not in COHERENCE_MODES:
            raise ValueError(f"recording_aug.coherence_mode={self.coherence_mode!r}: "
                             f"expected {COHERENCE_MODES}")
        if not self.enable:
            return
        if self.dirty.codec_prob > 0.0:
            raise NotImplementedError(
                "recording_aug.dirty_input.codec_prob > 0: codec simulation is a reserved "
                "seam. No controlled music-separation experiment isolating MP3/AAC/Opus "
                "exists (report §2.3), the local round-trip costs 140–170 ms per 8 s item "
                "(§3.5) — the whole per-item budget — and it needs an ffmpeg/licence audit.")
        wants_dry = self.rir.target_mode == "dry_source"
        if self.coherence_mode == "strict_sum":
            if wants_dry:
                raise ValueError(
                    "rir.target_mode='dry_source' under coherence_mode='strict_sum': dry "
                    "targets against a reverberant mixture are separation PLUS "
                    "dereverberation and do NOT satisfy mixture ≡ Σ targets. Set "
                    "coherence_mode: dereverberation if that is really the task.")
            if self.dirty.any_enabled:
                raise ValueError(
                    "recording_aug.dirty_input has a nonzero probability under "
                    "coherence_mode='strict_sum': noise/resample/quantize/clip degrade the "
                    "MIXTURE ONLY and intentionally break mixture ≡ Σ targets. Set "
                    "coherence_mode: clean_under_degraded_input to opt in.")
        elif self.coherence_mode == "dereverberation":
            if not wants_dry or self.rir.prob <= 0.0:
                raise ValueError(
                    "coherence_mode='dereverberation' needs rir.prob > 0 and "
                    "rir.target_mode='dry_source' — otherwise it is an ordinary strict-sum "
                    "arm mislabelled as a different task.")
            if self.dirty.any_enabled:
                raise ValueError("dirty_input needs coherence_mode="
                                 "'clean_under_degraded_input', not 'dereverberation'")
        if self.rir.prob > 0.0 and not 0.0 < self.rir.max_tail_seconds <= 3.0:
            raise ValueError(f"rir.max_tail_seconds={self.rir.max_tail_seconds}: expected "
                             "(0, 3] s — longer tails blow the FFT budget (report §3.5)")

    @property
    def any_stage_enabled(self) -> bool:
        return self.enable and max(
            self.device.prob, self.rir.prob, self.automation.mixbus_prob,
            self.automation.stem_prob, self.limit.prob,
            1.0 if self.limit.loudness_mode == "sampled" else 0.0,
            self.dirty.noise_prob, self.dirty.resample_prob, self.dirty.quantize_prob,
            self.dirty.clip_prob) > 0.0


